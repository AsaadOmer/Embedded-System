#define F_CPU 16000000UL
#include <util/delay.h>
#include <avr/interrupt.h>

#include "UTIL/std_types.h"
#include "UTIL/bit_math.h"

#include "MCAL/DIO/dio.h"
#include "MCAL/EXTI/EXTI.h"
#include "HAL/CLCD/CLCD_int.h"

// ?????? ???? ????? ??????
volatile u8 copy_u8Counter = 0;

// ISR ????? ?? INT0 (????? ?????)
ISR(INT0_vect) {
	if (copy_u8Counter < 9) {
		copy_u8Counter++;
	}
}

// ISR ????? ?? INT1 (????? ?????)
ISR(INT1_vect) {
	if (copy_u8Counter > 0) {
		copy_u8Counter--;
	}
}

int main(void) {
	// 1. ????? ????? ??? Push Buttons ??????? ?? ????? ??? Pull-Up ???????
	// PD2 = INT0 (Increment Button)
	DIO_voidSetPinDir(DIO_PORTD, DIO_PIN2, DIO_PIN_INPUT);
	DIO_voidSetPinVal(DIO_PORTD, DIO_PIN2, DIO_PIN_HIGH);

	// PD3 = INT1 (Decrement Button)
	DIO_voidSetPinDir(DIO_PORTD, DIO_PIN3, DIO_PIN_INPUT);
	DIO_voidSetPinVal(DIO_PORTD, DIO_PIN3, DIO_PIN_HIGH);

	// 2. ????? ??? External Interrupts ??? ??? Falling Edge
	EXTINT_voidChangeSenseControl(EXTINT_INT0, EXTINT_falling);
	EXTINT_voidChangeSenseControl(EXTINT_INT1, EXTINT_falling);

	// 3. ????? ??? INT0 ? INT1
	Enable_INT0();
	Enable_INT1();

	// 4. ????? ??? Global Interrupt (GIE)
	sei();

	// 5. ????? ???? ??? LCD
	CLCD_voidInit();

	// ??? ?????? ??????? (0)
	CLCD_voidSetCursorPosition(0, 0);
	CLCD_voidSendData('0' + copy_u8Counter);

	u8 lastValue = copy_u8Counter;

	while (1) {
		// ????? ?????? ??? ??? ???? ??????
		if (copy_u8Counter != lastValue) {
			CLCD_voidSetCursorPosition(0, 0);
			CLCD_voidSendData('0' + copy_u8Counter);
			lastValue = copy_u8Counter;
		}
	}

	return 0;
}