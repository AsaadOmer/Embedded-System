void CLCD_voidWriteNumber(u32 Copy_u32Number)
{
	u8 Local_u8Array[10];
	u8 Local_u8Index = 0;

	if (Copy_u32Number == 0)
	{
		CLCD_voidSendData('0');
		return;
	}

	while (Copy_u32Number > 0)
	{
		Local_u8Array[Local_u8Index] = (Copy_u32Number % 10) + '0';
		Copy_u32Number /= 10;
		Local_u8Index++;
	}

	while (Local_u8Index > 0)
	{
		Local_u8Index--;
		CLCD_voidSendData(Local_u8Array[Local_u8Index]);
	}
}

